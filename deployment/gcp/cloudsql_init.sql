-- deployment/gcp/cloudsql_init.sql
--
-- MOSAIC database schema. Run this once against a fresh Cloud SQL
-- (PostgreSQL 15+) database before running processing/run_processing.py
-- or starting the API.
--
-- Usage (see README.md "Create the database schema"):
--   psql "host=YOUR_SQL_IP port=5432 dbname=clinical_trial_db user=mosaic_user" -f deployment/gcp/cloudsql_init.sql
--
-- Embedding columns are vector(768) — matches Gemini's
-- gemini-embedding-001 model truncated to 768 dimensions
-- (see config/settings.py: gemini_embedding_dimensions).

CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ── STUDIES ─────────────────────────────────────────────────────
-- One row per clinical trial. Populated by processing/run_processing.py
-- before chunks (chunks.nct_id has a foreign key to this table).
CREATE TABLE IF NOT EXISTS studies (
    nct_id              TEXT PRIMARY KEY,
    title               TEXT,
    sponsor             TEXT,
    phase               TEXT,
    status              TEXT,
    conditions          TEXT[],
    interventions       TEXT[],
    primary_outcome     TEXT,
    secondary_outcomes  TEXT[],
    start_date          TEXT,
    completion_date     TEXT,
    results_posted      BOOLEAN,
    enrollment          INTEGER,
    gcs_path            TEXT
);

CREATE INDEX IF NOT EXISTS idx_studies_sponsor ON studies (sponsor);

-- ── CHUNKS ──────────────────────────────────────────────────────
-- Text chunks + embeddings for semantic search (processing/vector_store.py).
CREATE TABLE IF NOT EXISTS chunks (
    id                  BIGSERIAL PRIMARY KEY,
    nct_id              TEXT REFERENCES studies (nct_id) ON DELETE CASCADE,
    chunk_text          TEXT NOT NULL,
    embedding           VECTOR(768) NOT NULL,
    chunk_index         INTEGER NOT NULL,
    source              TEXT NOT NULL,
    UNIQUE (nct_id, chunk_index, source)
);

CREATE INDEX IF NOT EXISTS idx_chunks_nct_id ON chunks (nct_id);
CREATE INDEX IF NOT EXISTS idx_chunks_embedding
    ON chunks USING hnsw (embedding vector_cosine_ops);

-- ── EPISODES ────────────────────────────────────────────────────
-- Agent reasoning sessions (memory/episodic_store.py).
CREATE TABLE IF NOT EXISTS episodes (
    episode_id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    agent_name          TEXT NOT NULL,
    nct_id              TEXT,
    content             TEXT NOT NULL,
    outcome             TEXT,
    embedding           VECTOR(768) NOT NULL,
    created_at          TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_episodes_agent_name ON episodes (agent_name);
CREATE INDEX IF NOT EXISTS idx_episodes_embedding
    ON episodes USING hnsw (embedding vector_cosine_ops);

-- ── PROCEDURES ──────────────────────────────────────────────────
-- Agent reasoning rules — default + learned from HITL rejections
-- (memory/procedural_store.py).
CREATE TABLE IF NOT EXISTS procedures (
    procedure_id        UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    agent_name          TEXT NOT NULL,
    rule_text           TEXT NOT NULL,
    rule_type           TEXT DEFAULT 'learned',
    source              TEXT DEFAULT 'default',
    created_at          TIMESTAMPTZ DEFAULT NOW(),
    updated_at          TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_procedures_agent_name ON procedures (agent_name);

-- ── SPONSOR PROFILES ────────────────────────────────────────────
-- Accumulated sponsor track record (memory/semantic_store.py).
CREATE TABLE IF NOT EXISTS sponsor_profiles (
    sponsor             TEXT PRIMARY KEY,
    credibility_score   REAL DEFAULT 0.5,
    total_studies       INTEGER DEFAULT 0,
    results_posted      INTEGER DEFAULT 0,
    results_missing     INTEGER DEFAULT 0,
    broken_promises     INTEGER DEFAULT 0,
    avg_delay_days      REAL DEFAULT 0,
    last_updated        TIMESTAMPTZ DEFAULT NOW()
);

-- ── SIGNALS ─────────────────────────────────────────────────────
-- Findings generated by specialist agents (graph/hitl.py).
CREATE TABLE IF NOT EXISTS signals (
    signal_id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nct_id              TEXT,
    agent               TEXT NOT NULL,
    signal_type         TEXT,
    summary             TEXT,
    evidence            JSONB,
    confidence          REAL,
    status              TEXT DEFAULT 'pending',
    created_at          TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_signals_nct_id ON signals (nct_id);
CREATE INDEX IF NOT EXISTS idx_signals_status ON signals (status);

-- ── HITL REVIEWS ────────────────────────────────────────────────
-- Human-in-the-loop review queue for low-confidence signals
-- (graph/hitl.py).
CREATE TABLE IF NOT EXISTS hitl_reviews (
    review_id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    signal_id           UUID REFERENCES signals (signal_id) ON DELETE CASCADE,
    decision            TEXT DEFAULT 'pending',
    reviewer            TEXT,
    rejection_reason    TEXT,
    edit_summary        TEXT,
    created_at          TIMESTAMPTZ DEFAULT NOW(),
    reviewed_at         TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_hitl_reviews_decision ON hitl_reviews (decision);
